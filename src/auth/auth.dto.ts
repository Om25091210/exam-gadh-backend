import { ApiProperty } from '@nestjs/swagger';
import { IsIn, IsNotEmpty, IsOptional, IsString, Length, MaxLength } from 'class-validator';

export class GoogleLoginDto {
  @ApiProperty({ description: 'Google ID token from Google Sign-In' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(4096)
  idToken!: string;

  @ApiProperty({ description: 'Stable per-install id generated by the client' })
  @IsString()
  @Length(8, 128)
  deviceId!: string;

  @ApiProperty({ enum: ['android', 'web', 'ios'] })
  @IsIn(['android', 'web', 'ios'])
  platform!: string;

  @ApiProperty({ required: false })
  @IsOptional()
  @IsString()
  @MaxLength(120)
  deviceName?: string;
}

export class RefreshDto {
  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  @MaxLength(256)
  refreshToken!: string;
}
